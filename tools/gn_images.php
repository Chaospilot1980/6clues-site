<?php
// Lists every Game Night image (covers, document photos, portraits), marks which exist in assets/img/gn/,
// and writes an image brief for the missing ones to tools/gamenight_images.md.
// Usage: php tools/gn_images.php            (writes the brief, prints a summary)
declare(strict_types=1);
function e($s): string { return htmlspecialchars((string)$s, ENT_QUOTES, 'UTF-8'); }
require __DIR__ . '/../app/gamenight.php';
$root = dirname(__DIR__) . '/assets/img/gn/';
$people = json_decode(file_get_contents(__DIR__ . '/gn_people.json'), true);

const STYLE_SCENE = 'Style: cinematic, slightly grainy editorial photo-illustration with a film-noir mood; muted palette of ink black, warm paper cream and one deep red accent; fictional, no recognisable real people, no brand logos, no readable text or numbers.';
const STYLE_FACE = 'Style: head-and-shoulders portrait in a painterly graphic-novel noir style, muted palette of ink black, warm paper cream and one deep red accent, plain warm-grey background, soft side light, looking slightly past the camera; fictional person, no text.';

$all = [];
$order = gn_slugs(); usort($order, fn($a, $b) => strcmp(gn_case($a)["no"], gn_case($b)["no"]));
foreach ($order as $slug) {
    $c = gn_case($slug);
    $rows = [];
    $rows[] = ['type' => 'cover', 'file' => $c['cover']['file'], 'size' => '1600 × 1200 px (4:3)', 'use' => 'Case cover on the site and the printed front page', 'prompt' => $c['cover']['prompt'] . ' ' . STYLE_SCENE];
    foreach ($c['docs'] as $id => $d) if (!empty($d['img']))
        $rows[] = ['type' => 'evidence', 'file' => $d['img']['file'], 'size' => '1600 × 1200 px (4:3)', 'use' => "Evidence photo in document $id – caption: “{$d['img']['caption']}”", 'prompt' => $d['img']['prompt'] . ' ' . STYLE_SCENE];
    foreach ($c['suspects'] as $p) {
        $look = $people[$slug][$p['id']] ?? null;
        if (!$look) continue;
        $rows[] = ['type' => 'portrait', 'file' => "$slug/people/{$p['id']}.jpg", 'size' => '1024 × 1024 px (1:1)', 'use' => "Portrait of {$p['name']} – {$p['role']}", 'prompt' => "Portrait of a $look. " . STYLE_FACE];
    }
    foreach ($rows as &$r) $r['done'] = is_file($root . $r['file']);
    $all[$slug] = ['case' => $c, 'rows' => $rows];
}

$total = $done = 0;
$md = "# Six Clues – Game Night image brief\n\nGenerated by `php tools/gn_images.php`. Lists only the images that are **still missing**.\n\n";
$md .= "## How to deliver\n\n- **Format:** JPG, sRGB, quality about 80, each file under 500 KB.\n- **Sizes:** covers and evidence photos 1600 × 1200 px (4:3). Portraits 1024 × 1024 px (1:1).\n- **Names:** use exactly the file paths below (lower case, hyphens). Folders matter: `zero-point/people/leo-strand.jpg`.\n- **Delivery:** one ZIP whose top level contains the case folders (`zero-point/`, `the-glass-wall/` …). Partial ZIPs are fine – rerun this script to see what is still missing.\n- **Look across the set:** keep the same style for all portraits in a case, so the six people look like they belong to one story.\n\n";
foreach ($all as $slug => $x) {
    $miss = array_filter($x['rows'], fn($r) => !$r['done']);
    $total += count($x['rows']); $done += count($x['rows']) - count($miss);
    if (!$miss) continue;
    $md .= "## {$x['case']['no']} · {$x['case']['title']} (`$slug/`)\n\n";
    foreach ($miss as $r) $md .= "### `{$r['file']}`\n{$r['use']} · {$r['size']}\n\n> {$r['prompt']}\n\n";
}
$md .= "---\nStatus: $done of $total images delivered.\n";
file_put_contents(__DIR__ . '/gamenight_images.md', $md);
foreach ($all as $slug => $x) {
    $n = count($x['rows']); $d = count(array_filter($x['rows'], fn($r) => $r['done']));
    printf("%-26s %2d/%2d images\n", $slug, $d, $n);
}
echo "Total: $done of $total images delivered. Brief written to tools/gamenight_images.md\n";
