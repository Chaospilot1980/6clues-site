"""Lists the suspect portraits the daily mysteries still need and writes tools/mystery_images.md.
Order: library cases first, then daily cases by release date. Run automatically by export.py."""
import json, os, re, html, datetime
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
STYLE_SCENE = ('Style: cinematic, slightly grainy editorial photo-illustration with a film-noir mood; muted palette of ink black, warm paper cream and one deep red accent; '
               'fictional, no recognisable real people, no brand logos, no readable text or numbers.')
STYLE = ('Style: head-and-shoulders portrait in a painterly graphic-novel noir style, muted palette of ink black, warm paper cream and one deep red accent, '
         'plain warm-grey background, soft side light, looking slightly past the camera; fictional person, no text.')

STYLE_PHOTO = "Style: realistic photograph, slightly faded and grainy like real evidence, natural light for the time of day, same muted noir palette as the rest of the site; fictional people, faces small or turned away, no readable text, numbers or logos."

def slugify(x):
    import unicodedata
    x = unicodedata.normalize("NFKD", x).encode("ascii", "ignore").decode()
    return re.sub(r"[^a-z0-9]+", "-", x.lower()).strip("-")

def first_sentence(t):
    t = html.unescape(re.sub(r"<[^>]+>", "", t or "")).strip()
    return re.split(r"(?<=[.!?])\s", t)[0]

def main():
    raw = open(os.path.join(ROOT, "app", "mysteries.php")).read()
    body = raw.split("<<<'JSON_END'\n", 1)[1].rsplit("\nJSON_END", 1)[0]
    ms = json.loads(body)
    ms.sort(key=lambda m: (1 if m.get("daily") else 0, m.get("daily") or "", m.get("public") or ""))
    total = done = 0
    out = ["# Six Clues – images for the daily mysteries", "",
           "Generated by `python3 tools/m_images.py` (runs with every export). Lists only the images that are **still missing**.", "",
           "## How to deliver", "",
           "- **Format:** JPG, sRGB, quality about 80. Portraits 1024 × 1024 px (under 400 KB). Case covers 1600 × 1200 px, 4:3 (under 500 KB). Evidence photos (`photo-….jpg`) 1024 × 768 px, 4:3 (under 300 KB).",
           "- **Names:** exactly the paths below: `<case>/<person>.jpg`. The site looks for them in `assets/img/m/`.",
           "- **Delivery:** ZIP files whose top level contains the case folders. Partial ZIPs are fine.",
           "- **Order:** the cases at the top are already on the site; daily cases follow in release order.",
           "- **Style:** the same as the Game Night portraits, so the whole site looks like one series.", ""]
    for m in ms:
        rows = []
        cover = f"{m['slug']}/cover.jpg"
        total += 1
        if os.path.isfile(os.path.join(ROOT, "assets", "img", "m", cover)):
            done += 1
        else:
            rows.append((cover, None))
        for s in m["suspects"]:
            f = f"{m['slug']}/{slugify(s['name'])}.jpg"
            total += 1
            if os.path.isfile(os.path.join(ROOT, "assets", "img", "m", f)):
                done += 1; continue
            rows.append((f, s))
        for c in m["clues"]:
            ev = c.get("evidence") or ""
            if "{{PHOTO:" not in ev:
                continue
            t = re.search(r'<div style="[^"]*font-size: 19px[^"]*">(.*?)</div>', ev)
            title = re.sub(r"<[^>]+>", "", t.group(1)) if t else c.get("label", "")
            for pm in re.finditer(r"\{\{PHOTO:(?:[a-z0-9\-]+/)?([a-z0-9\-]+)\|([^}]*)\}\}</div>\s*<div[^>]*>(.*?)</div>\s*<div[^>]*>(.*?)</div>", ev, re.S):
                pid, label, when, cap = pm.groups()
                f = f"{m['slug']}/photo-{pid}.jpg"
                total += 1
                if os.path.isfile(os.path.join(ROOT, "assets", "img", "m", f)):
                    done += 1; continue
                rows.append((f, {"photo": True, "label": label, "time": re.sub(r"<[^>]+>", "", when), "cap": re.sub(r"<[^>]+>", "", cap), "title": title, "who": c.get("name", "")}))
        if not rows:
            continue
        when = f"daily case {m['daily']}" if m.get("daily") else "library – on the site now"
        out += [f"## {m['title']} ({when})", "", f"Setting: {first_sentence(m.get('intro_text') or m.get('intro'))}", ""]
        for f, s in rows:
            if s is None:
                out += [f"### `{f}`  (case cover, 1600 × 1200 px, 4:3)", f"> Cinematic scene illustration for the detective mystery “{m['title']}” ({m['crime'].lower()}): {first_sentence(m.get('intro_text') or m.get('intro'))} Show the place and the mood, no people in focus, no text, 4:3. {STYLE_SCENE}", ""]
                continue
            if s.get("photo"):
                kind = "grainy black-and-white security-camera still with a wide-angle lens" if re.search(r"cctv|camera –|cam\b|trail|doorbell|dashcam|security|infrared", s["title"], re.I) else "candid snapshot as taken with that camera"
                out += [f"### `{f}`  (evidence photo, 1024 × 768 px, 4:3)", f"> {kind.capitalize()} – “{s['label']}” at {s['time']}, from “{s['title']}” in the detective mystery “{m['title']}”: {s['cap']} The photo must show exactly this, because players use it as evidence. {STYLE_PHOTO}", ""]
                continue
            out += [f"### `{f}`", f"> Portrait of {s['name']}, {s['role']}, a character in the detective mystery “{m['title']}”. Age, look and clothing should fit the role and the setting. {STYLE}", ""]
    out += ["---", f"Status: {done} of {total} images delivered (one cover and six portraits per case, plus evidence photos)."]
    open(os.path.join(HERE, "mystery_images.md"), "w").write("\n".join(out) + "\n")
    print(f"Images: {done} of {total} delivered. List written to tools/mystery_images.md")

if __name__ == "__main__":
    main()
